const db = require('../config/db');
const AIService = require('./ai.service');
const ArticleModel = require('../models/article.model');
const PublishingService = require('./publishing.service');
const AIGenerationModel = require('../models/ai.generation.model');
const ActivityLog = require('../models/activity-log.model');
const { errorDetails } = require('../utils/http-errors');

class AutomationService {
    async runAutoGeneration(config) {
        console.log(`Starting automatic generation for topic: ${config.topic}`);
        try {
            // 1. Generate via AI
            const result = await AIService.generateArticle(config);

            // 2. Create article
            const articleId = await ArticleModel.create({
                ...result.data,
                status: config.auto_publish ? 'published' : 'draft'
            });

            try {
                await AIGenerationModel.create({
                    article_id: articleId,
                    provider: result.meta.provider,
                    model: result.meta.model,
                    prompt: JSON.stringify(config),
                    response: result.data,
                    status: 'completed'
                });
            } catch (historyError) {
                console.error('[Automation] Could not save generation history:', historyError.message);
                void ActivityLog.record({ category: 'errors', eventType: 'automation.history_save_failed', severity: 'warning', outcome: 'failure', actorType: 'system', source: 'automation', action: 'Generated article history could not be saved', targetType: 'article', targetId: articleId, details: { errorName: historyError.name, errorCode: historyError.code || null } });
            }

            // 3. If auto-publish is disabled, maybe schedule it
            if (!config.auto_publish && config.publication_time) {
                await PublishingService.schedule(articleId, config.publication_time);
            }

            void ActivityLog.record({ category: 'automation', eventType: 'automation.article_generated', severity: 'info', outcome: 'success', actorType: 'system', source: 'automation', action: 'Article generated by automation', targetType: 'article', targetId: articleId, details: { autoPublish: Boolean(config.auto_publish), scheduled: Boolean(!config.auto_publish && config.publication_time), provider: result.meta.provider, model: result.meta.model } });

            return { articleId, success: true };
        } catch (error) {
            console.error('Automation Error:', errorDetails(error));
            void ActivityLog.record({ category: 'errors', eventType: 'automation.generation_failed', severity: 'error', outcome: 'failure', actorType: 'system', source: 'automation', action: 'Automated article generation failed', details: { errorName: error.name, errorCode: error.code || null } });
            return { success: false, error: 'Automated generation could not be completed.' };
        }
    }
}

module.exports = new AutomationService();
